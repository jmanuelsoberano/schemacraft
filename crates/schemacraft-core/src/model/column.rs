use serde::{Deserialize, Serialize};
use ts_rs::TS;

use super::{Definition, SqlDataType};

/// A column of a table or view.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "model/")]
pub struct Column {
    /// Column name.
    pub name: String,
    /// One-based position in the object definition, so diagrams list columns in DDL order.
    pub ordinal_position: u32,
    /// Native data type.
    pub data_type: SqlDataType,
    /// Whether the column accepts `NULL`.
    pub is_nullable: bool,
    /// `DEFAULT` of the column. `None` means the column has none, except in a snapshot without
    /// an access profile (a 1.0 file), which recorded neither bound defaults nor defaults whose
    /// text the login could not read; `Some` holds the expression as stored by the database,
    /// e.g. `((0))` or `(getdate())`, or says why its text is missing:
    /// [`Definition::NotVisible`] when a default exists but the login cannot read it,
    /// [`Definition::NotRecorded`] when a 1.0 file could not tell whether there is one.
    pub default_expression: Option<Definition>,
    /// Whether values are generated by an identity sequence.
    pub is_identity: bool,
    /// Whether the column is computed from an expression.
    pub is_computed: bool,
}
